import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = file => readFile(path.join(root, file), 'utf8');
const css = await read('docs/acquisition-lens/webflow/first-look.css');
const engine = await read('public/acquisition-first-look.js');
const ui = await read('public/acquisition-first-look-ui.js');
for (const name of ['landing', 'screen']) {
  const template = await read('docs/acquisition-lens/webflow/' + name + '.template.html');
  const scripts = name === 'screen' ? '\n<script>\n' + engine + '\n' + ui + '\n</script>\n' : '';
  const embed = '<!-- Generated by npm run build:acquisition:screen; edit templates and source scripts. -->\n<style>\n' + css + '\n</style>\n' + template + scripts;
  await writeFile(path.join(root, 'docs/acquisition-lens/webflow/' + name + '.embed.html'), embed);
  const preview = embed.replaceAll('href="/acquisition-lens"', 'href="/acquisition-lens-preview.html"').replaceAll('href="/screen', 'href="/acquisition-screen-preview.html').replace(/href="\/(exit|about)?"/g, 'href="https://www.mikeye.com/$1"');
  const title = name === 'landing' ? 'Acquisition Lens — Buyer First-Look Screen' : 'Acquisition Lens — Screen an Opportunity';
  await writeFile(path.join(root, 'public/acquisition-' + (name === 'landing' ? 'lens' : 'screen') + '-preview.html'), '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="robots" content="noindex,nofollow"><title>' + title + '</title><style>body{margin:0}</style></head><body>' + preview + '</body></html>');
  console.log(name + ': generated Webflow embed and standalone preview');
}
